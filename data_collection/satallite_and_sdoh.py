def main():
    pipeline_t0 = time.time()
    log_sep(f"BIGBANG v9.0 — BAYESIAN SOTA PIPELINE (Year Range: {TARGET_YEAR_RANGE})")

    df_raw = pd.read_csv(DATA_FILE, low_memory=False)
    df_raw["GEOID"] = df_raw["GEOID"].astype(str).str.replace(r"\.0+$", "", regex=True).str.zfill(5)
    if "STATEFP" not in df_raw.columns: df_raw["STATEFP"] = df_raw["GEOID"].str[:2]
    df_raw = df_raw[~df_raw["STATEFP"].isin(EXCLUDE_STATEFP)].reset_index(drop=True)

    drop_prefixes = []
    if not INCLUDE_LIVESTOCK: drop_prefixes.append("LIVE_")
    if not INCLUDE_S1_SAR:    drop_prefixes.append("S1_")
    if not INCLUDE_S2_OPT:    drop_prefixes.append("S2_")
    if not INCLUDE_AIR_S5P:   drop_prefixes.extend(["AIR_", "PM25_"])
    if drop_prefixes:
        cols_to_drop = [c for c in df_raw.columns if any(c.startswith(p) for p in drop_prefixes)]
        df_raw = df_raw.drop(columns=cols_to_drop)

    df_target = df_raw[(df_raw["year"] >= TARGET_YEAR_RANGE[0]) & (df_raw["year"] <= TARGET_YEAR_RANGE[1])].dropna(subset=[TARGET_COL]).reset_index(drop=True)
    candidate_cols = [c for c in df_target.columns if c not in set(ID_COLS) | {TARGET_COL}]

    # ── Quick Temporal Alignment Aggregation ──
    for c in candidate_cols:
        if c.startswith(('S1_', 'S2_', 'AIR_', 'PM25_')) and c in df_target.columns:
            df_target[c] = df_target.groupby("GEOID")[c].transform('mean').astype('float32')

    unique_geoids = np.array(sorted(df_target["GEOID"].unique()))
    np.random.seed(RANDOM_STATE); np.random.shuffle(unique_geoids)
    holdout_geoids = set(unique_geoids[:max(5, int(len(unique_geoids) * HOLDOUT_FRAC))])
    is_holdout = df_target["GEOID"].isin(holdout_geoids).values

    X_dev = df_target.loc[~is_holdout, candidate_cols + ['STATEFP']].reset_index(drop=True)
    y_dev = df_target.loc[~is_holdout, TARGET_COL].reset_index(drop=True).astype('float32')
    g_dev = df_target.loc[~is_holdout, "GEOID"].reset_index(drop=True)

    X_hold = df_target.loc[is_holdout, candidate_cols + ['STATEFP']].reset_index(drop=True)
    y_hold = df_target.loc[is_holdout, TARGET_COL].reset_index(drop=True).astype('float32')

    # ── FOLD-SPECIFIC PRUNING PRE-COMPUTATION ──
    log_sep("Executing Fold-Specific Feature Pruning & Matrix Compilation")
    gkf = GroupKFold(n_splits=N_FOLDS)
    splits = []
    feature_survival = Counter()

    for fold_idx, (tr_idx, te_idx) in enumerate(gkf.split(X_dev, y_dev, g_dev)):
        t_f0 = time.time()
        X_tr_raw, X_te_raw = X_dev.iloc[tr_idx].copy(), X_dev.iloc[te_idx].copy()
        y_tr = y_dev.iloc[tr_idx]

        X_tr_raw['Spatial_Smoothed_LE'], X_te_raw['Spatial_Smoothed_LE'] = apply_spatial_smoothing(X_tr_raw, X_te_raw, y_tr, 'STATEFP')

        # Determine features strictly on Training fold
        kept_cols = fold_specific_pruning(X_tr_raw.drop(columns=['STATEFP']))
        feature_survival.update(kept_cols)

        m, lo, hi = preprocess_fit(X_tr_raw[kept_cols])
        X_tr_processed = preprocess_transform(X_tr_raw[kept_cols], m, lo, hi)
        X_te_processed = preprocess_transform(X_te_raw[kept_cols], m, lo, hi)

        splits.append({
            "X_train_num": X_tr_processed.astype('float32'),
            "X_test_num":  X_te_processed.astype('float32'),
            "y_train": y_tr,
            "y_test": y_dev.iloc[te_idx],
            "geoid_te": g_dev.iloc[te_idx].values,
            "kept_features": kept_cols
        })
        log(f"  Fold {fold_idx+1}: {len(kept_cols)} features survived strict pruning. ({(time.time()-t_f0):.1f}s)")

    # Save Feature Stability Report
    stability_df = pd.DataFrame.from_dict(feature_survival, orient='index', columns=['Survival_Count']).sort_values(by='Survival_Count', ascending=False)
    stability_df.index.name = 'Feature'
    stability_df.to_csv(OUTPUT_DIR / "feature_stability_report.csv")
    log("  -> Feature Stability Report Saved.")

    # ── BAYESIAN MODEL TUNING TOURNAMENT ──
    log_sep("Bayesian Model Tuning Tournament (Optuna)")
    best_models = {}
    active_models = [m for m, act in zip(["XGB", "CB", "LGB", "RF"], [USE_XGB, USE_CB, USE_LGB, USE_RF]) if act]

    for mname in active_models:
        log(f"\nOptuna Tuning {mname} ({N_ITER_SEARCH} Bayesian Trials)...")
        params, rmse, r2 = tune_model_optuna(splits, mname, n_iter=N_ITER_SEARCH)
        best_models[mname] = {"params": params, "rmse": rmse, "r2": r2}
        log(f"*** {mname} Bayesian Best CV-RMSE: {rmse:.4f} | R2: {r2:.4f} ***\n")

    winner_name = min(best_models.keys(), key=lambda k: best_models[k]["rmse"])
    best_params_winner = best_models[winner_name]["params"]
    log(f"🏆 BAYESIAN WINNER: {winner_name} (RMSE: {best_models[winner_name]['rmse']:.4f} | R2: {best_models[winner_name]['r2']:.4f})")

    # ── RETRAIN WINNER & EXTRACT OOF RESIDUALS ──
    log_sep("Extracting Clean OOF Residuals for Winner")
    all_oof_preds = []

    for fold_idx, spl in enumerate(splits):
        model = make_base_estimator(winner_name, best_params_winner)
        if winner_name in ["XGB", "CB", "LGB"]:
            model.fit(spl["X_train_num"], spl["y_train"], eval_set=[(spl["X_test_num"], spl["y_test"])], verbose=False)
        else:
            model.fit(spl["X_train_num"], spl["y_train"])

        p_te = model.predict(spl["X_test_num"])
        fold_df = pd.DataFrame({
            "GEOID": spl["geoid_te"], "Actual": spl["y_test"].values, "Predicted": p_te,
            "Residual": spl["y_test"].values - p_te, "Fold": fold_idx + 1
        })
        all_oof_preds.append(fold_df)

    pd.concat(all_oof_preds, ignore_index=True).to_csv(OUTPUT_DIR / f"cv_residuals_winner_{winner_name}.csv", index=False)
    log("  -> OOF Residuals Saved.")

    # ── 8. TRAIN WINNER ON FULL DEV & PREDICT HOLDOUT ──
    # To maintain honesty, we find features that survived in ALL folds to train the final model
    stable_features = stability_df[stability_df['Survival_Count'] == N_FOLDS].index.tolist()

    X_dev_raw, X_hold_raw = X_dev.copy(), X_hold.copy()
    X_dev_raw['Spatial_Smoothed_LE'], X_hold_raw['Spatial_Smoothed_LE'] = apply_spatial_smoothing(X_dev_raw, X_hold_raw, y_dev, 'STATEFP')

    m_f, lo_f, hi_f = preprocess_fit(X_dev_raw[stable_features])
    X_dev_imp = preprocess_transform(X_dev_raw[stable_features], m_f, lo_f, hi_f).astype('float32')
    X_hold_imp = preprocess_transform(X_hold_raw[stable_features], m_f, lo_f, hi_f).astype('float32')

    final_model = make_base_estimator(winner_name, best_params_winner)
    final_model.fit(X_dev_imp, y_dev)

    preds_hold = final_model.predict(X_hold_imp)
    h_r2 = r2_score(y_hold, preds_hold)
    h_rmse = np.sqrt(mean_squared_error(y_hold, preds_hold))

    log_sep("Holdout Evaluation")
    log(f"Hold-out R2: {h_r2:.4f} | RMSE: {h_rmse:.4f}")

    with open(OUTPUT_DIR / "final_model_winner.pkl", "wb") as f: pickle.dump(final_model, f)
    pd.DataFrame([{"Winner": winner_name, "Holdout_R2": h_r2, "Holdout_RMSE": h_rmse}]).to_csv(OUTPUT_DIR / "holdout_metrics.csv", index=False)

    log_sep(f"PIPELINE COMPLETE. Run Time: {(time.time() - pipeline_t0)/60:.1f} Minutes.")
    log(f"All assets saved to: {OUTPUT_DIR}")

if __name__ == "__main__":
    main()

