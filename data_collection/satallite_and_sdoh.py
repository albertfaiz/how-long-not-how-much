#  MULTI-SCALE REDUCER  (all server-side)
# =============================================================================
def build_reducer(ee, levels, percentiles):
    """Compose one ee.Reducer that produces L0/L1 stats in a single pass."""
    r = ee.Reducer.mean()
    if "L0" in levels:
        r = r.combine(ee.Reducer.median(), sharedInputs=True)
    if "L1" in levels:
        r = (r.combine(ee.Reducer.stdDev(), sharedInputs=True)
              .combine(ee.Reducer.skew(), sharedInputs=True)
              .combine(ee.Reducer.kurtosis(), sharedInputs=True)
              .combine(ee.Reducer.minMax(), sharedInputs=True)
              .combine(ee.Reducer.percentile(percentiles), sharedInputs=True))
    return r


def add_texture_bands(ee, img, scale):
    """L2: append within-county spatial-texture bands to the image."""
    out = img
    band_names = img.bandNames()

    def _per_band(bn):
        bn = ee.String(bn)
        b = img.select([bn])
        # Sobel gradient magnitude
        grad = b.gradient()
        gmag = grad.select("x").hypot(grad.select("y")).rename(bn.cat("_grad"))
        # local variance in 3x3 neighborhood
        lvar = b.reduceNeighborhood(
            reducer=ee.Reducer.variance(),
            kernel=ee.Kernel.square(1)).rename(bn.cat("_lvar"))
        return gmag.addBands(lvar)

    tex = ee.ImageCollection(band_names.map(_per_band)).toBands()
    return img.addBands(tex)


