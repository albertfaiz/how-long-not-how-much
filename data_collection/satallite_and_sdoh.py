def export_modality_year(ee, mod_key, spec, year, counties, levels, percentiles,
                         drive_folder, tile_scale, do_texture, do_popweight,
                         pop_collection):
    """Create ONE export task: county features for (modality, year)."""

    # FIX: Removed .clip(spec["region"]) so the projection math doesn't break
    img = ee.Image(spec["builder"](year))
    scale = spec["scale"]

    # base L0/L1 image
    work = img
    reducer = build_reducer(ee, levels, percentiles)

    # --- L2 texture ---
    if do_texture and "L2" in levels:
        work = add_texture_bands(ee, work, scale)
        # BUG FIX: Let the main reducer handle the texture bands.

    # First reduction: L0/L1(/L2) stats
    fc = work.reduceRegions(
        collection=counties, reducer=reducer, scale=scale, tileScale=tile_scale)

    # --- L3 population-weighting ---
    if do_popweight and "L3" in levels:
        # FIX: Removed .clip(spec["region"]) here as well!
        pop = pop_for_year(ee, pop_collection, year)
        num = img.multiply(pop)
        num = num.rename(img.bandNames().map(lambda b: ee.String(b).cat("_popnum")))
        combo = num.addBands(pop.rename("pop_den"))
        pop_fc = combo.reduceRegions(
            collection=counties, reducer=ee.Reducer.sum(), scale=scale,
            tileScale=tile_scale)

        # join back on GEOID
        join = ee.Join.inner()
        filt = ee.Filter.equals(leftField="GEOID", rightField="GEOID")
        joined = join.apply(fc, pop_fc, filt)
        def _merge(f):
            a = ee.Feature(f.get("primary"))
            b = ee.Feature(f.get("secondary"))
            return a.copyProperties(b, b.propertyNames())
        fc = ee.FeatureCollection(joined.map(_merge))

    # attach year + modality
    fc = fc.map(lambda f: f.set("year", year).set("modality", mod_key))

    # keep only county id props + computed stats (drop geometry to shrink CSV)
    fc = fc.select(propertySelectors=[".*"], retainGeometry=False)

    desc = f"{mod_key}_{year}"
    task = ee.batch.Export.table.toDrive(
        collection=fc,
        description=desc,
        folder=drive_folder,
        fileNamePrefix=desc,
        fileFormat="CSV")
    task.start()
    return task, desc


def pop_for_year(ee, pop_collection, year):
    """Nearest GHSL population epoch for a given year."""
    col = ee.ImageCollection(pop_collection)
    yimg = (col.filterDate(f"{max(1975,year-3)}-01-01", f"{min(2030,year+3)}-12-31")
            .first())
    return ee.Image(ee.Algorithms.If(yimg, yimg, col.mosaic())).rename("pop")


