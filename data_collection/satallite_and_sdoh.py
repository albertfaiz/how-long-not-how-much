# Helper to group columns by their modality/sensor prefix
def get_group(col):
    ignore_keys = ['GEOID', 'year', 'fips', 'NAME', 'STATEFP', 'COUNTYFP', 'MeanLifeExpectency', 'location_name']
    if col in ignore_keys:
        return 'Identifiers_and_Target'

    if '_' in col:
        parts = col.split('_')
        # Group complex USDA subsets together cleanly
        if parts[0] == 'USDA' and len(parts) > 1:
            return f"USDA_{parts[1]}"
        return parts[0]
    return 'Other'

# Core function to extract feature counts and true year ranges
def extract_metrics(df, source_name):
    groups = {}
    for col in df.columns:
        g = get_group(col)
        if g not in groups:
            groups[g] = []
        groups[g].append(col)

    metrics = {}
