# 5.  HIGH-THROUGHPUT TOURNAMENT (EARLY STOPPING ACTIVATED)
# =============================================================================
def make_base_estimator(model_name: str, params: dict | None = None):
    p = params or {}
    if model_name == "XGB": return xgb.XGBRegressor(**{"tree_method": "hist", "device": XGB_DEVICE, "random_state": RANDOM_STATE, "verbosity": 0, "n_jobs": N_JOBS, **p})
    if model_name == "CB":  return cb.CatBoostRegressor(**{"task_type": CB_TASK_TYPE, "random_seed": RANDOM_STATE, "verbose": False, **p})
    if model_name == "RF":  return RandomForestRegressor(**{"random_state": RANDOM_STATE, "n_jobs": N_JOBS, **p})

def tune_model_sequential(splits, mname, n_iter=N_ITER_SEARCH):
    spaces = {
        "XGB": {"n_estimators": [1000, 1500, 2000], "max_depth": [6, 8], "learning_rate": [0.03, 0.05], "subsample": [0.8, 0.9], "colsample_bytree": [0.8]},
        "CB":  {"iterations": [1000, 1500, 2000], "depth": [6, 8], "learning_rate": [0.03, 0.05], "l2_leaf_reg": [3, 5]},
        "RF":  {"n_estimators": [300, 500], "max_depth": [10, 15], "min_samples_leaf": [2, 4], "max_features": ["sqrt", 0.3]}
    }
    space = spaces[mname]
    keys, values = list(space.keys()), list(space.values())

    random.seed(RANDOM_STATE)
    trials = []
    for _ in range(n_iter):
        trial_dict = {k: random.choice(v) for k, v in zip(keys, values)}
        trials.append(trial_dict)

    best_rmse, best_r2, best_params = np.inf, -np.inf, None

    for i, p in enumerate(trials):
        log(f"    Trial {i+1}/{n_iter} | Params: {p}")
        rmses, r2s = [], []
        t_start = time.time()

        for fold_idx, spl in enumerate(splits):
            # Pre-sliced data loading
            X_tr, X_te = spl["X_train_num"], spl["X_test_num"]
            y_tr, y_te = spl["y_train"], spl["y_test"]

            model = make_base_estimator(mname, p)

            # Hardware-Specific Early Stopping
            if mname == "XGB":
                model.set_params(early_stopping_rounds=50)
                model.fit(X_tr, y_tr, eval_set=[(X_te, y_te)], verbose=False)
            elif mname == "CB":
                model.fit(X_tr, y_tr, eval_set=[(X_te, y_te)], early_stopping_rounds=50, verbose=False)
            else: # RF doesn't support early stopping
                model.fit(X_tr, y_tr)

            preds = model.predict(X_te)

            f_rmse = np.sqrt(mean_squared_error(y_te, preds))
            f_r2 = r2_score(y_te, preds)
            rmses.append(f_rmse)
            r2s.append(f_r2)

            log(f"      Fold {fold_idx+1} -> RMSE: {f_rmse:.4f} | R2: {f_r2:.4f}")

        mean_rmse = np.mean(rmses)
        mean_r2 = np.mean(r2s)
        log(f"    -> Trial {i+1} Mean RMSE: {mean_rmse:.4f} | Mean R2: {mean_r2:.4f} ({time.time()-t_start:.1f}s)\n")

        if mean_rmse < best_rmse:
            best_rmse, best_r2, best_params = mean_rmse, mean_r2, p

    return best_params, best_rmse, best_r2

