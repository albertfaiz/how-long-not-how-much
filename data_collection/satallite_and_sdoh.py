def process_and_save_dataset(input_path, output_path):
    print(f"\n⏳ Loading: {input_path.split('/')[-1]}...")
    df = pd.read_csv(input_path)
    initial_shape = df.shape[1]

    # A. Drop Dead Constants (Features where every row is exactly the same value)
    dead_constants = [col for col in df.columns if col not in meta_cols and df[col].nunique(dropna=True) <= 1]
    df = df.drop(columns=dead_constants)

    # B. Drop Exploded Features (Mathematical Artifacts)
    # Safely caps at ±50,000,000 (LA County pop is ~10M, so this safely catches divide-by-zero errors)
    exploded_features = []
    numeric_cols = df.select_dtypes(include=[np.number]).columns
    for col in numeric_cols:
        if col in meta_cols:
            continue
        if np.isinf(df[col]).any() or df[col].max() > 50000000 or df[col].min() < -50000000:
            exploded_features.append(col)

    df = df.drop(columns=exploded_features)

    # C. Prefix all Livestock Columns
    rename_dict = {}
    for col in livestock_cols:
        if col in df.columns:
            # If it's an engineered livestock feature, replace "ENG_Livestock" with "LIVE_ENG" for clean grouping
            if col.startswith('ENG_Livestock'):
                rename_dict[col] = col.replace('ENG_Livestock', 'LIVE_ENG')
            else:
                rename_dict[col] = f"LIVE_{col}"

    df = df.rename(columns=rename_dict)

    # D. Save to Descriptive File Name
    df.to_csv(output_path, index=False)

    # E. Report Actions
    print(f"   🗑️ Removed {len(dead_constants)} Dead Constants.")
    if len(dead_constants) > 0: print(f"      (e.g., {dead_constants[:3]})")

    print(f"   💥 Removed {len(exploded_features)} Exploded Artifacts.")
    if len(exploded_features) > 0: print(f"      (e.g., {exploded_features[:3]})")

    print(f"   🏷️ Renamed {len(rename_dict)} Livestock Columns (Added 'LIVE_' prefix).")
    print(f"   💾 Saved Dataset to: {output_path.split('/')[-1]}")
    print(f"   📊 Final Feature Count: {initial_shape} -> {df.shape[1]} columns")

