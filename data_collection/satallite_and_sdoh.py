def make_base_estimator(model_name: str, params: dict):
    if model_name == "XGB": return xgb.XGBRegressor(**{"tree_method": "hist", "device": XGB_DEVICE, "random_state": RANDOM_STATE, "verbosity": 0, "n_jobs": N_JOBS, **params})
    if model_name == "CB":  return cb.CatBoostRegressor(**{"task_type": CB_TASK_TYPE, "random_seed": RANDOM_STATE, "verbose": False, **params})
    if model_name == "LGB": return lgb.LGBMRegressor(**{"device_type": "cpu", "random_state": RANDOM_STATE, "n_jobs": N_JOBS, "verbose": -1, **params})
    if model_name == "RF":  return RandomForestRegressor(**{"random_state": RANDOM_STATE, "n_jobs": N_JOBS, **params})

def tune_model_optuna(splits, mname, n_iter=N_ITER_SEARCH):

    def objective(trial):
        if mname == "XGB":
            params = {
                "n_estimators": trial.suggest_categorical("n_estimators", [1000, 1500, 2000]),
                "max_depth": trial.suggest_int("max_depth", 6, 10),
                "learning_rate": trial.suggest_float("learning_rate", 0.01, 0.08, log=True),
                "subsample": trial.suggest_float("subsample", 0.7, 0.9),
                "colsample_bytree": trial.suggest_float("colsample_bytree", 0.7, 0.9),
                "min_child_weight": trial.suggest_int("min_child_weight", 1, 10),
                "reg_alpha": trial.suggest_float("reg_alpha", 1e-3, 10.0, log=True),
                "reg_lambda": trial.suggest_float("reg_lambda", 1e-3, 10.0, log=True)
            }
        elif mname == "CB":
            params = {
                "iterations": trial.suggest_categorical("iterations", [1000, 1500, 2000]),
                "depth": trial.suggest_int("depth", 6, 10),
                "learning_rate": trial.suggest_float("learning_rate", 0.01, 0.08, log=True),
                "l2_leaf_reg": trial.suggest_float("l2_leaf_reg", 1.0, 10.0),
                "random_strength": trial.suggest_float("random_strength", 1e-3, 10.0, log=True)
            }
        elif mname == "LGB":
            params = {
                "n_estimators": trial.suggest_categorical("n_estimators", [1000, 1500]),
                "max_depth": trial.suggest_int("max_depth", 6, 12),
                "num_leaves": trial.suggest_int("num_leaves", 31, 255),
                "learning_rate": trial.suggest_float("learning_rate", 0.01, 0.08, log=True),
                "subsample": trial.suggest_float("subsample", 0.7, 0.9),
                "reg_alpha": trial.suggest_float("reg_alpha", 1e-3, 10.0, log=True),
                "reg_lambda": trial.suggest_float("reg_lambda", 1e-3, 10.0, log=True)
            }
        else: # RF
            params = {
                "n_estimators": trial.suggest_categorical("n_estimators", [500, 1000, 2000]),
                "max_depth": trial.suggest_categorical("max_depth", [15, 25, None]),
                "min_samples_leaf": trial.suggest_int("min_samples_leaf", 1, 5),
                "max_features": trial.suggest_categorical("max_features", ["sqrt", 0.3])
            }

        tr_rmses, te_rmses, te_r2s = [], [], []

        for fold_idx, spl in enumerate(splits):
            X_tr = spl["X_train_num"]
            X_te = spl["X_test_num"]
            y_tr = spl["y_train"]
            y_te = spl["y_test"]

            model = make_base_estimator(mname, params)

            if mname == "XGB":
                model.set_params(early_stopping_rounds=50)
                model.fit(X_tr, y_tr, eval_set=[(X_te, y_te)], verbose=False)
            elif mname == "CB":
                model.fit(X_tr, y_tr, eval_set=[(X_te, y_te)], early_stopping_rounds=50, verbose=False)
            elif mname == "LGB":
                model.fit(X_tr, y_tr, eval_set=[(X_te, y_te)], callbacks=[lgb.early_stopping(stopping_rounds=50, verbose=False)])
            else:
                model.fit(X_tr, y_tr)

            p_tr = model.predict(X_tr)
            p_te = model.predict(X_te)

            tr_rmses.append(np.sqrt(mean_squared_error(y_tr, p_tr)))
            te_rmses.append(np.sqrt(mean_squared_error(y_te, p_te)))
            te_r2s.append(r2_score(y_te, p_te))

        # Store metrics in trial for logging extraction later
        trial.set_user_attr("mean_tr_rmse", np.mean(tr_rmses))
        trial.set_user_attr("mean_te_r2", np.mean(te_r2s))

        return np.mean(te_rmses)

    sampler = optuna.samplers.TPESampler(seed=RANDOM_STATE)
    study = optuna.create_study(direction="minimize", sampler=sampler)

    # Run optimization safely (n_jobs=1 stops GPU deadlocks while evaluating trials)
    study.optimize(objective, n_trials=n_iter, n_jobs=1)

    best_trial = study.best_trial
    best_params = best_trial.params
    best_te_rmse = best_trial.value
    best_te_r2 = best_trial.user_attrs["mean_te_r2"]

    log(f"  -> Best Optuna Params: {best_params}")
    return best_params, best_te_rmse, best_te_r2

