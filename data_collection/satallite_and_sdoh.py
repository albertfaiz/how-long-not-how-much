def compute_metrics(y_true, y_pred) -> dict:
    r2 = r2_score(y_true, y_pred)
    rmse = np.sqrt(mean_squared_error(y_true, y_pred))
    mae = mean_absolute_error(y_true, y_pred)
    medae = median_absolute_error(y_true, y_pred)
    # SMAPE handles values near zero gracefully unlike standard MAPE
    smape = np.mean(2.0 * np.abs(y_pred - y_true) / (np.abs(y_true) + np.abs(y_pred))) * 100
    return {"R2": r2, "RMSE": rmse, "MAE": mae, "MedAE": medae, "SMAPE": smape}

def bootstrap_ci(metric_array, alpha=0.05):
    """Calculates exactly 95% Confidence Intervals for robust reporting."""
    lower = np.percentile(metric_array, (alpha / 2) * 100)
    upper = np.percentile(metric_array, (1 - alpha / 2) * 100)
    mean_val = np.mean(metric_array)
    return f"{mean_val:.4f} ± {np.std(metric_array):.4f} [{lower:.4f}, {upper:.4f}]"

