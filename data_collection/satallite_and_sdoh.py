def make_base_estimator(model_name: str, params: dict | None = None):
    p = params or {}
    if model_name == "XGB": return xgb.XGBRegressor(**{"tree_method": "hist", "device": XGB_DEVICE, "random_state": RANDOM_STATE, "verbosity": 0, "n_jobs": N_JOBS, **p})
    if model_name == "CB":  return cb.CatBoostRegressor(**{"task_type": CB_TASK_TYPE, "random_seed": RANDOM_STATE, "verbose": False, **p})
    if model_name == "RF":  return RandomForestRegressor(**{"random_state": RANDOM_STATE, "n_jobs": N_JOBS, **p})

def tune_model_sequential(splits, mname, n_iter=N_ITER_SEARCH):
    # EXPANDED SOTA GRIDS
    spaces = {
        "XGB": {"n_estimators": [500, 1000, 1500], "max_depth": [6, 8, 10], "learning_rate": [0.01, 0.03, 0.05], "subsample": [0.8, 0.9], "colsample_bytree": [0.7, 0.8]},
        "CB":  {"iterations": [500, 1000, 1500], "depth": [6, 8, 10], "learning_rate": [0.01, 0.03, 0.05], "l2_leaf_reg": [3, 5, 7]},
        "RF":  {"n_estimators": [1000, 1500, 2000], "max_depth": [15, 25, None], "min_samples_leaf": [1, 2, 4], "max_features": ["sqrt", 0.3]}
    }
    space = spaces[mname]
    keys, values = list(space.keys()), list(space.values())

    random.seed(RANDOM_STATE)
    trials = []
    for _ in range(n_iter):
        trial_dict = {k: random.choice(v) for k, v in zip(keys, values)}
        trials.append(trial_dict)

    best_te_rmse, best_te_r2, best_params = np.inf, -np.inf, None
    best_oof_preds = []

    for i, p in enumerate(trials):
        log(f"    Trial {i+1}/{n_iter} | Params: {p}")
        tr_rmses, te_rmses, tr_r2s, te_r2s = [], [], [], []
        oof_preds = []
        t_start = time.time()

        for fold_idx, spl in enumerate(splits):
            X_tr, X_te = spl["X_train_num"], spl["X_test_num"]
            y_tr, y_te = spl["y_train"], spl["y_test"]

            model = make_base_estimator(mname, p)

            if mname == "XGB":
                model.set_params(early_stopping_rounds=50)
                model.fit(X_tr, y_tr, eval_set=[(X_te, y_te)], verbose=False)
            elif mname == "CB":
                model.fit(X_tr, y_tr, eval_set=[(X_te, y_te)], early_stopping_rounds=50, verbose=False)
            else:
                model.fit(X_tr, y_tr)

            p_tr = model.predict(X_tr)
            p_te = model.predict(X_te)

            f_tr_rmse = np.sqrt(mean_squared_error(y_tr, p_tr))
            f_te_rmse = np.sqrt(mean_squared_error(y_te, p_te))
            f_tr_r2 = r2_score(y_tr, p_tr)
            f_te_r2 = r2_score(y_te, p_te)

            tr_rmses.append(f_tr_rmse); te_rmses.append(f_te_rmse)
            tr_r2s.append(f_tr_r2); te_r2s.append(f_te_r2)

            # Save for residual plotting
            fold_df = pd.DataFrame({
                "GEOID": spl["geoid_te"], "Actual": y_te.values, "Predicted": p_te,
                "Residual": y_te.values - p_te, "Fold": fold_idx + 1
            })
            oof_preds.append(fold_df)

            log(f"      Fold {fold_idx+1} -> TRAIN (R2: {f_tr_r2:.4f}, RMSE: {f_tr_rmse:.4f}) | TEST (R2: {f_te_r2:.4f}, RMSE: {f_te_rmse:.4f})")

        mean_tr_rmse, mean_te_rmse = np.mean(tr_rmses), np.mean(te_rmses)
        mean_tr_r2, mean_te_r2 = np.mean(tr_r2s), np.mean(te_r2s)

        log(f"    -> Trial {i+1} Mean TRAIN (R2: {mean_tr_r2:.4f}) | Mean TEST (R2: {mean_te_r2:.4f}, RMSE: {mean_te_rmse:.4f}) ({time.time()-t_start:.1f}s)\n")

        if mean_te_rmse < best_te_rmse:
            best_te_rmse, best_te_r2, best_params = mean_te_rmse, mean_te_r2, p
            best_oof_preds = pd.concat(oof_preds, ignore_index=True)

    return best_params, best_te_rmse, best_te_r2, best_oof_preds

