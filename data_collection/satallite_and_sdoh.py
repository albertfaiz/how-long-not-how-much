def build_registry(ee):
    """Return {modality_key: dict(...)} . Called after ee.Initialize()."""
    US = ee.Geometry.Polygon(US_REGION_COORDS, None, False)

    def yr_range(y):
        return ee.Filter.date(f"{y}-01-01", f"{y}-12-31")

    reg = {}

    # ----- NIGHT LIGHTS : two sources, harmonized ---------------------------
    def ntl_viirs(y):
        col = (ee.ImageCollection("NOAA/VIIRS/DNB/MONTHLY_V1/VCMSLCFG")
               .filter(yr_range(y)).select("avg_rad"))
        return col.mean().rename("ntl").set("ntl_source", "VIIRS")

    def ntl_dmsp(y):
        img = (ee.ImageCollection("NOAA/DMSP-OLS/NIGHTTIME_LIGHTS")
               .filter(yr_range(y)).select("stable_lights"))
        return img.mean().rename("ntl").set("ntl_source", "DMSP")

    reg["NTL_VIIRS"] = dict(builder=ntl_viirs, scale=500, years=(2012, 2023),
                            bands=["ntl"], region=US)
    reg["NTL_DMSP"]  = dict(builder=ntl_dmsp, scale=1000, years=(2000, 2013),
                            bands=["ntl"], region=US)

    # ----- PM2.5 : ACAG V6 (global, ~1 km, annual, 2000-2022) ---------------
    def pm25(y):
        col = ee.ImageCollection("projects/sat-io/open-datasets/GLOBAL-SATELLITE-PM25/ANNUAL")
        img = col.filter(yr_range(y)).select('b1').mean()
        return img.rename("pm25")

    reg["PM25"] = dict(builder=pm25, scale=1000, years=(2000, 2022),
                       bands=["pm25"], region=US)

    # ----- MODIS LST : day & night, 1 km, 8-day (2000+) ---------------------
    def lst(y):
        col = ee.ImageCollection("MODIS/061/MOD11A2").filter(yr_range(y))
        day = col.select("LST_Day_1km").mean().multiply(0.02).subtract(273.15).rename("lst_day")
        ngt = col.select("LST_Night_1km").mean().multiply(0.02).subtract(273.15).rename("lst_night")
        return day.addBands(ngt)

    reg["LST"] = dict(builder=lst, scale=1000, years=(2000, 2023),
                      bands=["lst_day", "lst_night"], region=US)

    # ----- MODIS NDVI/EVI : 250 m, 16-day (2000+) ---------------------------
    def ndvi(y):
        col = ee.ImageCollection("MODIS/061/MOD13Q1").filter(yr_range(y))
        nd = col.select("NDVI").mean().multiply(0.0001).rename("ndvi")
        ev = col.select("EVI").mean().multiply(0.0001).rename("evi")
        return nd.addBands(ev)

    reg["NDVI"] = dict(builder=ndvi, scale=250, years=(2000, 2023),
                       bands=["ndvi", "evi"], region=US)

    # ----- DEM / TOPOGRAPHY : static, 30 m ----------------------------------
    def dem(_y):
        d = ee.ImageCollection("USGS/3DEP/10m_collection").mosaic().select("elevation").rename("elev")
        slope = ee.Terrain.slope(d).rename("slope")
        return d.addBands(slope)

    reg["DEM"] = dict(builder=dem, scale=30, years=(2000, 2000),  # static: one epoch
                      bands=["elev", "slope"], region=US, static=True)

    # ----- LANDSAT : 30 m surface reflectance NDVI (full record) ------------
    def landsat_ndvi(y):
        def sr(col_id, red, nir):
            c = (ee.ImageCollection(col_id).filter(yr_range(y))
                 .filterBounds(US))
            def _ndvi(im):
                nd = im.normalizedDifference([nir, red]).rename("ls_ndvi")
                return nd
            return c.map(_ndvi).select("ls_ndvi").mean()
        img = ee.Algorithms.If(
            ee.Number(y).lt(2013),
            sr("LANDSAT/LT05/C02/T1_L2", "SR_B3", "SR_B4"),
            sr("LANDSAT/LC08/C02/T1_L2", "SR_B4", "SR_B5"))
        return ee.Image(img).rename("ls_ndvi")

    reg["LANDSAT_NDVI"] = dict(builder=landsat_ndvi, scale=30, years=(2000, 2023),
                               bands=["ls_ndvi"], region=US)

    # ----- AIR QUALITY : Sentinel-5P NO2 (2018+, ~1 km resampled) -----------
    def s5p_no2(y):
        col = (ee.ImageCollection("COPERNICUS/S5P/OFFL/L3_NO2")
               .filter(yr_range(y)).select("tropospheric_NO2_column_number_density"))
        return col.mean().rename("no2")

    reg["AIR_NO2"] = dict(builder=s5p_no2, scale=1113, years=(2019, 2023),
                          bands=["no2"], region=US)

    # ----- PRISM ------------------------------------------------------------
    def prism(y):
        col = ee.ImageCollection("OREGONSTATE/PRISM/AN81m").filter(yr_range(y))
        tmean = col.select("tmean").mean().rename("tmean")
        ppt   = col.select("ppt").sum().rename("ppt")
        return tmean.addBands(ppt)

    reg["PRISM"] = dict(builder=prism, scale=4000, years=(2000, 2023),
                        bands=["tmean", "ppt"], region=US, coarse_control=True)

    return reg


