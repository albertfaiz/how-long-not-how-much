def fold_specific_pruning(X_tr: pd.DataFrame) -> list:
    """Removes NZV and Collinear features strictly within a training fold to prevent leakage."""
    X_ = X_tr.replace([np.inf, -np.inf], np.nan)

    # 1. Missingness filter
    miss_frac = X_.isna().mean()
    keep = miss_frac[miss_frac <= MAX_MISSING_FRAC].index.tolist()
    X_imp = X_[keep].fillna(X_[keep].median(numeric_only=True))

    # 2. Near-Zero Variance (also catches absolute constants and identical duplicates implicitly)
    variances = X_imp.var(numeric_only=True)
    nzv = variances[variances < NEAR_ZERO_VAR_THRESH].index.tolist()
    keep = [c for c in keep if c not in nzv]

    # 3. Correlation Matrix (Drops near-duplicates > 0.98)
    if len(keep) > 1:
        sub = X_imp[keep].sample(n=min(20_000, len(X_imp)), random_state=RANDOM_STATE)
        with np.errstate(invalid="ignore", divide="ignore"):
            cm = np.abs(np.corrcoef(sub.values, rowvar=False))
        np.fill_diagonal(cm, 0.0)
        cm = np.where(np.isnan(cm), 0.0, cm)

        cols = sub.columns.tolist()
        keep_mask = np.ones(len(cols), dtype=bool)
        mean_corr = cm.mean(axis=0)

        for idx_c in np.argsort(-mean_corr):
            if not keep_mask[idx_c]: continue
            partners = np.where((cm[idx_c] > CORR_THRESHOLD) & keep_mask)[0]
            for idx_p in partners:
                if idx_p == idx_c or not keep_mask[idx_p]: continue
                drop_idx = idx_p if len(cols[idx_c]) <= len(cols[idx_p]) else idx_c
                keep_mask[drop_idx] = False
                if drop_idx == idx_c: break
        keep = [cols[i] for i in range(len(cols)) if keep_mask[i]]

    return keep

def preprocess_transform(X: pd.DataFrame, medians, lower_clip, upper_clip) -> pd.DataFrame:
    numeric_cols = X.select_dtypes(include=[np.number]).columns
    X[numeric_cols] = X[numeric_cols].replace([np.inf, -np.inf], np.nan).fillna(medians).clip(lower=lower_clip, upper=upper_clip, axis=1).fillna(0.0)
    X[numeric_cols] = X[numeric_cols].astype('float32')
    return X

