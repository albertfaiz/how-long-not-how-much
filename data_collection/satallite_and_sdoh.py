def fold_specific_preprocess(X_tr, X_te, y_tr):
    """Executes Imputation and RobustScaling strictly inside the fold."""
    X_tr_c = X_tr.copy()
    X_te_c = X_te.copy()

    # 1. State-Mean Spatial Smoothing
    if 'STATEFP' in X_tr_c.columns:
        state_means = y_tr.groupby(X_tr_c['STATEFP']).mean().to_dict()
        global_mean = y_tr.mean()
        X_tr_c['Spatial_Smoothed_LE'] = X_tr_c['STATEFP'].map(state_means).fillna(global_mean)
        X_te_c['Spatial_Smoothed_LE'] = X_te_c['STATEFP'].map(state_means).fillna(global_mean)
        X_tr_c = X_tr_c.drop(columns=['STATEFP'])
        X_te_c = X_te_c.drop(columns=['STATEFP'])

    # 2. Fold-Specific Median Imputation
    medians = X_tr_c.median()
    X_tr_c = X_tr_c.fillna(medians)
    X_te_c = X_te_c.fillna(medians)

    # 3. Robust Scaler (Resistant to spatial outliers)
    scaler = RobustScaler()
    X_tr_scaled = pd.DataFrame(scaler.fit_transform(X_tr_c), columns=X_tr_c.columns, index=X_tr_c.index)
    X_te_scaled = pd.DataFrame(scaler.transform(X_te_c), columns=X_te_c.columns, index=X_te_c.index)

    return X_tr_scaled.astype('float32'), X_te_scaled.astype('float32')

