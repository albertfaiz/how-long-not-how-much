def cluster_bootstrap_ci(df, group_col='GEOID', true_col='Actual', pred_col='Predicted', n_iterations=2000, alpha=0.05):
    """
    SOTA: Cluster Bootstrap. Resamples by GEOID rather than individual rows
    to preserve spatial dependence structure.
    """
    unique_groups = df[group_col].unique()
    n_groups = len(unique_groups)

    r2_boot, rmse_boot, mae_boot = [], [], []
    np.random.seed(42)

    # Adaptive convergence tracking
    running_means = []

    for i in range(n_iterations):
        # Sample groups with replacement
        sampled_groups = np.random.choice(unique_groups, size=n_groups, replace=True)

        # Build the bootstrap sample dataframe (vectorized for speed)
        # We use a mapping trick to efficiently reconstruct the duplicated groups
        group_counts = pd.Series(sampled_groups).value_counts()

        # Filter original df to only the sampled groups
        boot_df = df[df[group_col].isin(group_counts.index)]

        # Duplicate rows based on how many times their group was sampled
        repeats = boot_df[group_col].map(group_counts).values
        y_t = np.repeat(boot_df[true_col].values, repeats)
        y_p = np.repeat(boot_df[pred_col].values, repeats)

        r2, rmse, mae = compute_metrics(y_t, y_p)
        r2_boot.append(r2); rmse_boot.append(rmse); mae_boot.append(mae)

        running_means.append(np.mean(r2_boot))

        # Adaptive stopping check (stabilized variance)
        if i > 500 and i % 100 == 0:
            if np.std(running_means[-100:]) < 1e-5:
                log(f"    -> Cluster Bootstrap converged early at {i} iterations.")
                break

    lower_p, upper_p = (alpha / 2) * 100, (1 - alpha / 2) * 100

    return {
        "R2_CI": (np.percentile(r2_boot, lower_p), np.percentile(r2_boot, upper_p)),
        "RMSE_CI": (np.percentile(rmse_boot, lower_p), np.percentile(rmse_boot, upper_p)),
        "MAE_CI": (np.percentile(mae_boot, lower_p), np.percentile(mae_boot, upper_p)),
        "Iters": len(r2_boot)
    }

def conformal_prediction_intervals(y_true, y_pred, alpha=0.10):
    """Proper CV+ Split Conformal Prediction for Error Bounds."""
