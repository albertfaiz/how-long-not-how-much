def load_counties(ee, asset, conus_only=False):
    fc = ee.FeatureCollection(asset)
    def _norm(f):
        return f.set("GEOID", f.get("GEOID"))
    fc = fc.map(_norm)
    if conus_only:
        non_conus = ee.List(["02", "15", "60", "66", "69", "72", "78"])
        fc = fc.filter(ee.Filter.inList("STATEFP", non_conus).Not())
    return fc


