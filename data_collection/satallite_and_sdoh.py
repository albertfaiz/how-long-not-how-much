def apply_spatial_smoothing(df_train, df_val, y_train, state_col):
    state_means = y_train.groupby(df_train[state_col]).mean().to_dict()
    global_mean = y_train.mean()
    smoothed_train = df_train[state_col].map(state_means).fillna(global_mean).astype('float32')
