    if len(models_data) > 1:
        se_arrays = [(df['Actual'] - df['Predicted'])**2 for df in models_data.values()]
        model_names = list(models_data.keys())

        stat, p_val = stats.friedmanchisquare(*se_arrays)
        log(f"  -> Friedman Test across {len(model_names)} models: p-value = {p_val:.4e}")

        if p_val < 0.05:
            log("  ✅ Significant variance detected. Proceeding to Holm-Bonferroni corrected pairwise tests.")

            pvals_raw, comparisons, d_z_scores, winners = [], [], [], []
            for i in range(len(model_names)):
                for j in range(i+1, len(model_names)):
                    m1, m2 = model_names[i], model_names[j]
                    se1, se2 = se_arrays[i], se_arrays[j]

