def bootstrap_confidence_intervals(y_true, y_pred, n_iterations=1000, alpha=0.05):
    """Generates 95% CIs via empirical bootstrapping."""
    n = len(y_true)
    r2_boot, rmse_boot, mae_boot = [], [], []

    np.random.seed(42)
    for _ in range(n_iterations):
        idx = np.random.choice(n, n, replace=True)
        y_t, y_p = y_true[idx], y_pred[idx]

        r2, rmse, mae = compute_metrics(y_t, y_p)
        r2_boot.append(r2); rmse_boot.append(rmse); mae_boot.append(mae)

    lower_p, upper_p = (alpha / 2) * 100, (1 - alpha / 2) * 100

    return {
        "R2_CI": (np.percentile(r2_boot, lower_p), np.percentile(r2_boot, upper_p)),
        "RMSE_CI": (np.percentile(rmse_boot, lower_p), np.percentile(rmse_boot, upper_p)),
        "MAE_CI": (np.percentile(mae_boot, lower_p), np.percentile(mae_boot, upper_p))
    }

def conformal_prediction_intervals(y_true, y_pred, alpha=0.10):
    """Split Conformal Prediction for 90% Error Bounds."""
    n = len(y_true)
    residuals = np.abs(y_true - y_pred)

    # Calculate the quantile for the desired coverage
    q_level = np.ceil((n + 1) * (1 - alpha)) / n
    q_val = np.quantile(residuals, min(q_level, 1.0))

    # Calculate empirical coverage
    lower_bounds = y_pred - q_val
    upper_bounds = y_pred + q_val
    coverage = np.mean((y_true >= lower_bounds) & (y_true <= upper_bounds)) * 100

    return q_val, coverage

def calibration_analysis(y_true, y_pred):
    """Regresses Actual ~ Predicted to find calibration slope and intercept."""
    X = sm.add_constant(y_pred)
    model = sm.OLS(y_true, X).fit()
    intercept, slope = model.params
    return slope, intercept

