        y_tr = y_dev.iloc[tr_idx]

        X_tr_raw['Spatial_Smoothed_LE'], X_te_raw['Spatial_Smoothed_LE'] = apply_spatial_smoothing(X_tr_raw, X_te_raw, y_tr, 'STATEFP')
        m, lo, hi = preprocess_fit(X_tr_raw.drop(columns=['STATEFP']))

