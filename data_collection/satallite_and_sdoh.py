def overlap_fraction(modality: str, target_range: tuple = TARGET_YEAR_RANGE) -> float:
    if modality not in MODALITY_YEAR_RANGES: return 1.0
    m_lo, m_hi = MODALITY_YEAR_RANGES[modality]
    t_lo, t_hi = target_range
    overlap = max(0, min(m_hi, t_hi) - max(m_lo, t_lo) + 1)
    span = t_hi - t_lo + 1
    return overlap / span if span > 0 else 0.0

def is_leakage(col: str) -> bool:
    name = col.lower()
    if name == TARGET_COL.lower(): return False
    return any(re.search(p, name) for p in [r"life.*expect", r"expect.*life", r"^mortality", r"death_rate", r"^yll", r"^yld"])

