def train_evaluate_catboost(X_train, y_train, X_test, y_test, groups_train):
    """Uses a grouped inner-validation split for true zero-leakage early stopping."""
    # GroupShuffleSplit ensures the same county doesn't end up in both inner-train and inner-val
    gss = GroupShuffleSplit(n_splits=1, test_size=0.15, random_state=CONFIG.random_state)
    inner_tr_idx, inner_val_idx = next(gss.split(X_train, y_train, groups=groups_train))

    X_tr_in, y_tr_in = X_train.iloc[inner_tr_idx], y_train.iloc[inner_tr_idx]
    X_val_in, y_val_in = X_train.iloc[inner_val_idx], y_train.iloc[inner_val_idx]

    cb_params = {
        'iterations': CONFIG.cb_iterations, 'depth': CONFIG.cb_depth,
        'learning_rate': CONFIG.cb_learning_rate, 'l2_leaf_reg': CONFIG.cb_l2_leaf_reg,
        'task_type': 'GPU', 'verbose': False, 'random_seed': CONFIG.random_state
    }

    model = cb.CatBoostRegressor(**cb_params)
    try:
        model.fit(X_tr_in, y_tr_in, eval_set=[(X_val_in, y_val_in)], early_stopping_rounds=50)
    except Exception as e:
        log(f"  [!] GPU Exception Caught: {str(e)}. Executing Automatic CPU Fallback...")
        cb_params['task_type'] = 'CPU'
        model = cb.CatBoostRegressor(**cb_params)
        model.fit(X_tr_in, y_tr_in, eval_set=[(X_val_in, y_val_in)], early_stopping_rounds=50)

    preds = model.predict(X_test)
    return compute_metrics(y_test, preds)

