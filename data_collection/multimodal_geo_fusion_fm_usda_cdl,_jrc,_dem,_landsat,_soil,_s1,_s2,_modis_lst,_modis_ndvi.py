    ax2.set_xlabel('Actual Life Expectancy (Years)')
    ax2.set_ylabel('Absolute Error (Years)')
    ax2.set_title('🎯 Outlier Magnitude', fontsize=12, fontweight='bold')
    cbar = plt.colorbar(scatter, ax=ax2)
    cbar.set_label('Bias (years)')
    ax2.grid(alpha=0.3)

