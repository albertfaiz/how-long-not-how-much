import os
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from scipy import stats

def generate_publication_figures(df):
    print("\n=== GENERATING PUBLICATION-READY FIGURES ===")

    # 1. Set explicit save path to your Google Drive folder
    SAVE_DIR = '/content/drive/MyDrive/Canopy_Height_Meta_v2'
    os.makedirs(SAVE_DIR, exist_ok=True)

    # Set high-quality journal theme
    sns.set_theme(style="ticks", context="paper", font_scale=1.2)

    # ---------------------------------------------------------
    # FIGURE 1: Horizontal Stratification (1m vs 5m Cover)
    # ---------------------------------------------------------
    if 'canopy_cover_1m_mean' in df.columns and 'canopy_cover_5m_mean' in df.columns:
        fig, axes = plt.subplots(1, 2, figsize=(14, 6), dpi=300)

        # Panel A
        sns.kdeplot(data=df, x='canopy_cover_1m_mean', fill=True, color='mediumseagreen',
                    label='> 1m (All Vegetation)', ax=axes[0], alpha=0.5)
        sns.kdeplot(data=df, x='canopy_cover_5m_mean', fill=True, color='darkgreen',
                    label='> 5m (Established Forest)', ax=axes[0], alpha=0.5)
        axes[0].set_title('A. Distribution of Canopy Cover Densities', fontweight='bold')
        axes[0].set_xlabel('Fraction of County Covered')
        axes[0].set_ylabel('Density')
        axes[0].legend()

        # Panel B
        sns.scatterplot(data=df, x='canopy_cover_1m_mean', y='canopy_cover_5m_mean',
                        alpha=0.6, edgecolor='k', ax=axes[1])

        lims = [0, max(df['canopy_cover_1m_mean'].max(), df['canopy_cover_5m_mean'].max())]
        axes[1].plot(lims, lims, 'r--', alpha=0.75, zorder=0, label='1:1 Ratio (Perfect Overlap)')

        slope, intercept, r_value, p_value, std_err = stats.linregress(df['canopy_cover_1m_mean'], df['canopy_cover_5m_mean'])
        axes[1].text(0.05, 0.95, f'$R^2 = {r_value**2:.3f}$\nSlope = {slope:.2f}',
                     transform=axes[1].transAxes, fontsize=12, verticalalignment='top',
                     bbox=dict(boxstyle='round', facecolor='white', alpha=0.8))

        axes[1].set_title('B. Vegetation vs. Forest Correlation', fontweight='bold')
        axes[1].set_xlabel('Mean Cover > 1m')
        axes[1].set_ylabel('Mean Cover > 5m')
        axes[1].legend(loc='lower right')

        plt.tight_layout()
        plt.savefig(os.path.join(SAVE_DIR, "Fig1_Canopy_Stratification.png"))
        plt.show() # <-- Renders the image in your notebook

    # ---------------------------------------------------------
    # FIGURE 2: Vertical Structural Complexity (Percentiles)
    # ---------------------------------------------------------
    p_cols = [f'canopy_height_p{i}' for i in [10, 20, 30, 40, 50, 60, 70, 80, 90, 99] if f'canopy_height_p{i}' in df.columns]

    if p_cols and 'NAME' in df.columns:
        fig, axes = plt.subplots(1, 2, figsize=(16, 6), dpi=300)

        # Panel A
        sns.violinplot(data=df[p_cols], palette="YlGnBu", inner="quartile", ax=axes[0])
        axes[0].set_title('A. County-Level Vertical Structure Distribution', fontweight='bold')
        axes[0].set_xticklabels([c.split('_')[-1] for c in p_cols], rotation=45)
        axes[0].set_ylabel('Height (meters)')

        # Panel B
        if 'canopy_cover_5m_mean' in df.columns:
            top_5 = df.nlargest(5, 'canopy_cover_5m_mean')
            for _, row in top_5.iterrows():
                axes[1].plot([int(c.split('p')[-1]) for c in p_cols], row[p_cols], marker='o', label=row['NAME'])

            axes[1].set_title('B. Vertical Profiles of Top 5 Forested Counties', fontweight='bold')
            axes[1].set_xlabel('Percentile')
            axes[1].set_ylabel('Height (meters)')
            axes[1].legend(title='County')
            axes[1].grid(True, linestyle='--', alpha=0.6)

        plt.tight_layout()
        plt.savefig(os.path.join(SAVE_DIR, "Fig2_Structural_Complexity.png"))
        plt.show()

    # ---------------------------------------------------------
    # FIGURE 3: Mean vs. Maximum Canopy Dynamics
    # ---------------------------------------------------------
    if 'canopy_height_mean' in df.columns and 'canopy_height_max' in df.columns:
        fig, axes = plt.subplots(1, 2, figsize=(14, 6), dpi=300)

        # Panel A
        sns.regplot(data=df, x='canopy_height_mean', y='canopy_height_max',
                    scatter_kws={'alpha':0.6, 'edgecolor':'w'}, line_kws={'color':'red'}, ax=axes[0])
        axes[0].set_title('A. Mean vs. Maximum Height Relationship', fontweight='bold')
        axes[0].set_xlabel('Mean Canopy Height (m)')
        axes[0].set_ylabel('Maximum Canopy Height (m)')

        max_row = df.loc[df['canopy_height_max'].idxmax()]
        axes[0].annotate(max_row['NAME'],
                         (max_row['canopy_height_mean'], max_row['canopy_height_max']),
                         xytext=(10, -10), textcoords='offset points', weight='bold')

        # Panel B
        if 'canopy_height_stdDev' in df.columns:
            sns.histplot(df['canopy_height_stdDev'], kde=True, color='purple', ax=axes[1])
            axes[1].set_title('B. Variance in Forest Height (StdDev)', fontweight='bold')
            axes[1].set_xlabel('Height Standard Deviation (m)')
            axes[1].set_ylabel('Frequency')

            median_std = df['canopy_height_stdDev'].median()
            axes[1].axvline(median_std, color='k', linestyle='dashed', linewidth=2)
            axes[1].text(median_std*1.05, axes[1].get_ylim()[1]*0.9, f'Median: {median_std:.2f}m', weight='bold')

        plt.tight_layout()
        plt.savefig(os.path.join(SAVE_DIR, "Fig3_Mean_vs_Max.png"))
        plt.show()

    # ---------------------------------------------------------
    # FIGURE 4: Top Counties Extreme Value Analysis
    # ---------------------------------------------------------
    if 'canopy_height_max' in df.columns and 'canopy_height_p99' in df.columns:
        fig, axes = plt.subplots(1, 2, figsize=(16, 7), dpi=300)

        top_15 = df.nlargest(15, 'canopy_height_max')

        # Panel A
        sns.barplot(data=top_15, x='NAME', y='canopy_height_max',
                    hue='NAME', palette='viridis', legend=False, ax=axes[0])
        axes[0].set_title('A. Absolute Maximum Tree Height by County', fontweight='bold')
        axes[0].set_xlabel('')
        axes[0].set_ylabel('Height (m)')
        axes[0].tick_params(axis='x', rotation=45)

        # Panel B
        sns.barplot(data=top_15, x='NAME', y='canopy_height_p99',
                    hue='NAME', palette='magma', legend=False, ax=axes[1])
        axes[1].set_title('B. 99th Percentile Height for Top Counties', fontweight='bold')
        axes[1].set_xlabel('')
        axes[1].set_ylabel('Height (m)')
        axes[1].tick_params(axis='x', rotation=45)

        plt.tight_layout()
        plt.savefig(os.path.join(SAVE_DIR, "Fig4_Extremes_Analysis.png"))
        plt.show()

    # ---------------------------------------------------------
    # FIGURE 5: Feature Space Separation
    # ---------------------------------------------------------
    if 'canopy_cover_5m_mean' in df.columns and 'canopy_height_p90' in df.columns:
        g = sns.JointGrid(data=df, x='canopy_cover_5m_mean', y='canopy_height_p90', space=0, height=8, ratio=4)

        g.plot_joint(plt.hexbin, gridsize=20, cmap='Blues', mincnt=1, edgecolors='none')
        g.plot_marginals(sns.kdeplot, fill=True, color='navy')

        g.fig.suptitle('Fig 5. ML Feature Space: Forest Density vs. 90th Percentile Height',
                       fontweight='bold', y=1.02, fontsize=14)
        g.ax_joint.set_xlabel('Fraction of County with > 5m Canopy')
        g.ax_joint.set_ylabel('90th Percentile Canopy Height (m)')
        g.ax_joint.grid(True, linestyle=':', alpha=0.7)

        plt.savefig(os.path.join(SAVE_DIR, "Fig5_Feature_Space.png"), dpi=300, bbox_inches='tight')
        plt.show()

    print(f"✓ Successfully generated and saved 5 figures to: {SAVE_DIR}")

# RUN IT
if master_df is not None:
    generate_publication_figures(master_df)

