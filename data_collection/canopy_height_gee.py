"""Plotting canopy height on for the USA using our generated csv"""

import os
import pandas as pd
import geopandas as gpd
import matplotlib.pyplot as plt
from mpl_toolkits.axes_grid1 import make_axes_locatable

def generate_canopy_map(csv_path):
    print("\n=== GENERATING US CANOPY HEIGHT MAP ===")

    # 1. Setup paths
    SAVE_DIR = '/content/drive/MyDrive/Canopy_Height_Meta_v2'
    os.makedirs(SAVE_DIR, exist_ok=True)

    # Load your master dataset
    df = pd.read_csv(csv_path, dtype={'GEOID': str})

    # 2. Download Official US Census Shapefiles (20m resolution is optimal for nation-wide maps)
    print("Downloading US Census County and State boundaries...")
    counties_url = "https://www2.census.gov/geo/tiger/GENZ2021/shp/cb_2021_us_county_20m.zip"
    states_url = "https://www2.census.gov/geo/tiger/GENZ2021/shp/cb_2021_us_state_20m.zip"

    gdf_counties = gpd.read_file(counties_url)
    gdf_states = gpd.read_file(states_url)

    # 3. Filter to Contiguous US (Lower 48) for a clean, focused map
    # Excluding Alaska, Hawaii, and Territories to avoid massive blank ocean spaces
    exclude_fips = ['02', '15', '60', '66', '69', '72', '78']
    gdf_counties = gdf_counties[~gdf_counties['STATEFP'].isin(exclude_fips)]
    gdf_states = gdf_states[~gdf_states['STATEFP'].isin(exclude_fips)]

    # 4. Reproject to Albers Equal Area (EPSG:5070) for accurate US curvature
    print("Reprojecting geometries to Albers Equal Area...")
    gdf_counties = gdf_counties.to_crs("EPSG:5070")
    gdf_states = gdf_states.to_crs("EPSG:5070")

    # 5. Merge Spatial Boundaries with your CSV Data
    # 'GEOID' is our golden key connecting the shapefile to your ML features
    merged = gdf_counties.merge(df, on='GEOID', how='left')

    # 6. Build the Visual Figure
    print("Plotting map...")
    fig, ax = plt.subplots(1, 1, figsize=(20, 12), dpi=300)

    # Plot County Data (Greens colormap: 0=White, Max=Dark Green)
    merged.plot(column='canopy_height_max',
                cmap='Greens',
                linewidth=0.2,          # Very light county boundaries
                edgecolor='0.8',        # Light grey color for county lines
                ax=ax,
                missing_kwds={'color': 'whitesmoke'}) # Counties with no data will be off-white

    # Overlay State Boundaries (Bold and transparent)
    gdf_states.plot(ax=ax, facecolor='none', edgecolor='black', linewidth=1.2)

    # 7. Add a Professional Colorbar
    divider = make_axes_locatable(ax)
    cax = divider.append_axes("right", size="2%", pad=0.1)

    sm = plt.cm.ScalarMappable(cmap='Greens', norm=plt.Normalize(vmin=0, vmax=merged['canopy_height_max'].max()))
    sm._A = []
    cbar = fig.colorbar(sm, cax=cax)
    cbar.set_label('Absolute Maximum Canopy Height (meters)', fontsize=14, fontweight='bold', labelpad=15)
    cbar.ax.tick_params(labelsize=12)

    # 8. Title and Formatting
    ax.set_title('Maximum Canopy Height by U.S. County\n(Derived from Meta High-Resolution CHMv2)',
                 fontsize=22, fontweight='bold', pad=20)
    ax.axis('off') # Turn off the ugly latitude/longitude axis box

    # 9. Add Annotation Box with Key Stats for the Reader
    max_row = df.loc[df['canopy_height_max'].idxmax()]
    stats_text = (
        f"Data Summary:\n"
        f"────────────────\n"
        f"Counties Mapped: {df['GEOID'].nunique():,}\n"
        f"National Max: {max_row['canopy_height_max']}m ({max_row['NAME']} County, {max_row['STATEFP']})\n"
        f"National Mean Max: {df['canopy_height_max'].mean():.1f}m\n"
        f"National Median Max: {df['canopy_height_max'].median():.1f}m"
    )

    props = dict(boxstyle='round,pad=0.8', facecolor='white', alpha=0.9, edgecolor='gray', linewidth=1.5)
    ax.text(0.02, 0.05, stats_text, transform=ax.transAxes, fontsize=14,
            verticalalignment='bottom', bbox=props, fontfamily='monospace')

    # 10. Save and Display
    save_file = os.path.join(SAVE_DIR, "Fig6_National_Canopy_Map.png")
    plt.tight_layout()
    plt.savefig(save_file, bbox_inches='tight', dpi=300)
    plt.show()

    print(f"✓ Map successfully saved to: {save_file}")

