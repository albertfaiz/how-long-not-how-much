import ee
import os
import time
from google.colab import drive

# 1. Authenticate and Initialize
try:
    ee.Initialize(project=__import__('os').environ.get('EE_PROJECT', 'your-earth-engine-project'))
except:
    ee.Authenticate()
    ee.Initialize(project=__import__('os').environ.get('EE_PROJECT', 'your-earth-engine-project'))

# 2. Mount Drive
drive.mount('/content/drive')

# ------------------- CONFIGURATION -------------------
TEST_MODE = False           # Set to False to run all US states
SCALE = 10                  # 10m resolution (Sweet spot for CHM)
QUEUE_LIMIT = 2800          # Max concurrent GEE tasks (Limit is 3000)
SLEEP_TIME = 180            # Seconds to wait when queue is full (3 mins)

FOLDER = 'Canopy_Height_Meta_v2'
BASE = f'/content/drive/MyDrive/{FOLDER}'
os.makedirs(BASE, exist_ok=True)

# ------------------- DATA PREPARATION -------------------
# US Counties Geometry (Excluding Territories for standard US run)
counties_fc = ee.FeatureCollection('TIGER/2018/Counties') \
    .filter(ee.Filter.inList('STATEFP', ['02','15','60','66','69','72','78']).Not())

# Get list of states to iterate over
if TEST_MODE:
    state_list = ['06'] # Just California for testing
else:
    state_list = counties_fc.aggregate_array('STATEFP').distinct().getInfo()

def get_chm_image():
    """
    Loads Meta CHMv2 Collection, mosaics it into a single image,
    and adds canopy cover density proxy bands.
    """
    # Load collection and mosaic to fix the "not an image" error
    chm_collection = ee.ImageCollection('projects/meta-forest-monitoring-okw37/assets/CanopyHeight')
    chm = chm_collection.mosaic().select([0]).rename('canopy_height')

    # Create binary masks for coverage (Density proxies)
    cover_1m = chm.gte(1).rename('canopy_cover_1m')
    cover_5m = chm.gte(5).rename('canopy_cover_5m')

    return chm.addBands([cover_1m, cover_5m])

# ------------------- QUEUE MANAGEMENT -------------------
def get_active_tasks():
    """Counts how many tasks are currently RUNNING or READY."""
    tasks = ee.batch.Task.list()
    active = [t for t in tasks if t.state in ['RUNNING', 'READY']]
    return len(active)

def manage_queue():
    """Pauses script execution if we are hitting the GEE task limit."""
    active_count = get_active_tasks()
    while active_count >= QUEUE_LIMIT:
        print(f"  [QUEUE FULL] {active_count} tasks active. Sleeping for {SLEEP_TIME/60} minutes...")
        time.sleep(SLEEP_TIME)
        active_count = get_active_tasks()

# ------------------- MAIN EXECUTION LOOP -------------------
print("=== STARTING META CHMv2 EXTRACTION ===")
chm_image = get_chm_image()

# The Reducer: 10 Percentiles + Mean + StdDev + Max
# This combination gives you a complete structural profile of the canopy
custom_reducer = ee.Reducer.percentile([10, 20, 30, 40, 50, 60, 70, 80, 90, 99]) \
    .combine(ee.Reducer.mean(), '', True) \
    .combine(ee.Reducer.stdDev(), '', True) \
    .combine(ee.Reducer.max(), '', True)

for state in state_list:
    # 1. Skip if already downloaded
    file_name = f"meta_chm_v2_state_{state}.csv"
    file_path = os.path.join(BASE, file_name)
    if os.path.exists(file_path) and os.path.getsize(file_path) > 0:
        print(f"Skipping State {state}: File already exists.")
        continue

    # 2. Check Queue Limit
    manage_queue()

    # 3. Filter geometry to current state
    state_counties = counties_fc.filter(ee.Filter.eq('STATEFP', state))

    try:
        # 4. Extract Statistics
        stats = chm_image.reduceRegions(
            collection=state_counties,
            reducer=custom_reducer,
            scale=SCALE,
            tileScale=16  # High tileScale to prevent memory limits
        )

        # 5. Clean up output (Keep only useful keys for easy merging later)
        def preserve_keys(feature):
            return ee.Feature(None, {
                'STATEFP': feature.get('STATEFP'),
                'COUNTYFP': feature.get('COUNTYFP'),
                'NAME': feature.get('NAME')
            }).copyProperties(feature, feature.propertyNames())

        stats_clean = stats.map(preserve_keys)

        # 6. Submit Task to GEE
        task = ee.batch.Export.table.toDrive(
            collection=stats_clean,
            folder=FOLDER,
            description=f"Task_CHMv2_{state}",
            fileNamePrefix=f"meta_chm_v2_state_{state}",
            fileFormat='CSV'
        )
        task.start()
        print(f"→ Task Submitted: State {state}")

    except Exception as e:
        print(f"!! ERROR on State {state}: {e}")

print("\n=== ALL TASKS SUBMITTED TO GEE ===")
print(f"Check your Google Earth Engine Code Editor 'Tasks' tab to monitor progress.")
print(f"Files will appear in Drive: {BASE}")

"""Buliding the master clean csv"""

import os
import glob
import pandas as pd

# ------------------- CONFIG -------------------
FOLDER = '/content/drive/MyDrive/Canopy_Height_Meta_v2'
MASTER_FILE = os.path.join(FOLDER, 'US_Master_Canopy_CHMv2.csv')

def build_master_dataset():
    print("=== STARTING ROBUST AGGREGATION ===")

    search_pattern = os.path.join(FOLDER, 'meta_chm_v2_state_*.csv')
    csv_files = glob.glob(search_pattern)

    if not csv_files:
        print("!! No files found. Check your GEE exports and folder path.")
        return None

    print(f"Found {len(csv_files)} state files. Processing...")

    df_list = []

    for file in csv_files:
        try:
            # Force read FIPS columns as strings to catch any existing leading zeros
            df = pd.read_csv(file, dtype={'STATEFP': str, 'COUNTYFP': str, 'GEOID': str})

            if df.empty: continue

            # STRIP BLOAT: We only want ML features and core keys.
            # Dropping extra TIGER census columns and GEE artifacts.
            cols_to_drop = [
                'system:index', '.geo', 'ALAND', 'AWATER', 'CBSAFP', 'CLASSFP',
                'COUNTYNS', 'CSAFP', 'FUNCSTAT', 'INTPTLAT', 'INTPTLON',
                'LSAD', 'METDIVFP', 'MTFCC', 'NAMELSAD'
            ]
            df = df.drop(columns=[c for c in cols_to_drop if c in df.columns])

            # BULLETPROOF KEYS: Force strict 2-digit State and 3-digit County codes
            df['STATEFP'] = df['STATEFP'].astype(str).str.replace(r'\.0$', '', regex=True).str.zfill(2)
            df['COUNTYFP'] = df['COUNTYFP'].astype(str).str.replace(r'\.0$', '', regex=True).str.zfill(3)

            # OVERWRITE GEOID to guarantee strict 5-digit string format (e.g., "06055")
            df['GEOID'] = df['STATEFP'] + df['COUNTYFP']

            df_list.append(df)

        except Exception as e:
            print(f"  - !! Error reading {os.path.basename(file)}: {e}")

    if df_list:
        master_df = pd.concat(df_list, ignore_index=True)

        # Organize: Put Core Keys First, then cover stats, then height stats
        front_cols = ['GEOID', 'STATEFP', 'COUNTYFP', 'NAME']
        cover_cols = sorted([c for c in master_df.columns if 'cover' in c])
        height_cols = sorted([c for c in master_df.columns if 'height' in c])

        final_col_order = front_cols + cover_cols + height_cols
        master_df = master_df[final_col_order]

        master_df.to_csv(MASTER_FILE, index=False)
        print(f"\n=== SUCCESS ===")
        print(f"Master file created: {MASTER_FILE}")
        print(f"Total Counties Processed: {len(master_df)}")

        return master_df
    return None

# RUN
master_df = build_master_dataset()

