"""Lets try to plt canopy height a bit more vibrant NASA style"""

import os
import pandas as pd
import geopandas as gpd
import matplotlib.pyplot as plt
import matplotlib.gridspec as gridspec

def generate_nasa_style_map(csv_path):
    print("\n=== GENERATING NASA-STYLE NATIONAL MAP ===")

    # 1. Setup paths
    SAVE_DIR = '/content/drive/MyDrive/Canopy_Height_Meta_v2'
    os.makedirs(SAVE_DIR, exist_ok=True)

    # Load your master dataset - Ensure GEOID is read as string
    df = pd.read_csv(csv_path, dtype={'GEOID': str, 'STATEFP': str, 'COUNTYFP': str})

    # 2. Download Official US Census Shapefiles (20m optimal for this scale)
    print("Downloading US Census geometries (Counties & States)...")
    counties_url = "https://www2.census.gov/geo/tiger/GENZ2021/shp/cb_2021_us_county_20m.zip"
    states_url = "https://www2.census.gov/geo/tiger/GENZ2021/shp/cb_2021_us_state_20m.zip"

    gdf_counties = gpd.read_file(counties_url)
    gdf_states = gpd.read_file(states_url)

    # --- THE FIX: Prevent Pandas from creating _x and _y duplicate columns ---
    # We drop the CSV's version of these columns so we only keep the Shapefile's version
    df_for_merge = df.drop(columns=['STATEFP', 'COUNTYFP', 'NAME'], errors='ignore')
    merged = gdf_counties.merge(df_for_merge, on='GEOID', how='left')

    # 3. SEGMENT DATASET BY REGION (Needed for reprojections)
    print("Segmenting regions (Lower 48, Alaska, Hawaii)...")
    exclude_fips = ['02', '15', '60', '66', '69', '72', '78']

    # Contiguous 48 (Lower 48)
    gdf_48_merged = merged[~merged['STATEFP'].isin(exclude_fips)].copy()
    gdf_48_states = gdf_states[~gdf_states['STATEFP'].isin(exclude_fips)].copy()

    # Alaska
    gdf_ak_merged = merged[merged['STATEFP'] == '02'].copy()
    gdf_ak_states = gdf_states[gdf_states['STATEFP'] == '02'].copy()

    # Hawaii
    gdf_hi_merged = merged[merged['STATEFP'] == '15'].copy()
    gdf_hi_states = gdf_states[gdf_states['STATEFP'] == '15'].copy()

    # 4. ROBUST REPROJECTIONS (Accurate shapes for all 50 states)
    print("Reprojecting geometries for accurate mapping...")
    gdf_48_merged = gdf_48_merged.to_crs("EPSG:5070") # Conus Albers
    gdf_48_states = gdf_48_states.to_crs("EPSG:5070")

    gdf_ak_merged = gdf_ak_merged.to_crs("EPSG:3338") # Alaska Albers
    gdf_ak_states = gdf_ak_states.to_crs("EPSG:3338")

    gdf_hi_merged = gdf_hi_merged.to_crs("EPSG:26904") # NAD83 / UTM zone 4N for HI
    gdf_hi_states = gdf_hi_states.to_crs("EPSG:26904")

    # 5. BUILD COMPLEX MULTI-PANEL LAYOUT (NASA Aesthetic)
    print("Building high-resolution layout...")
    fig = plt.figure(figsize=(24, 14), dpi=300)
    gs = gridspec.GridSpec(5, 5)

    VMAX = df['canopy_height_max'].max()
    cmap_chosen = 'viridis'

    # -- A. Plot Lower 48 --
    ax_48 = plt.subplot(gs[0:5, 0:5])
    gdf_48_merged.plot(column='canopy_height_max', cmap=cmap_chosen, linewidth=0.1,
                       edgecolor='0.6', vmin=0, vmax=VMAX, ax=ax_48, missing_kwds={'color': 'whitesmoke'})
    gdf_48_states.plot(ax=ax_48, facecolor='none', edgecolor='white', linewidth=1.2)
    ax_48.axis('off')
    ax_48.set_title('Absolute Maximum Canopy Height by U.S. County', fontsize=26, fontweight='bold', pad=20)

    # -- B. Plot Alaska --
    ax_ak = plt.subplot(gs[3:5, 0:2])
    gdf_ak_merged.plot(column='canopy_height_max', cmap=cmap_chosen, linewidth=0.1,
                       edgecolor='0.6', vmin=0, vmax=VMAX, ax=ax_ak, missing_kwds={'color': 'whitesmoke'})
    gdf_ak_states.plot(ax=ax_ak, facecolor='none', edgecolor='white', linewidth=1.0)
    ax_ak.axis('off')

    # -- C. Plot Hawaii --
    ax_hi = plt.subplot(gs[3:5, 3:5])
    gdf_hi_merged.plot(column='canopy_height_max', cmap=cmap_chosen, linewidth=0.1,
                       edgecolor='0.6', vmin=0, vmax=VMAX, ax=ax_hi, missing_kwds={'color': 'whitesmoke'})
    gdf_hi_states.plot(ax=ax_hi, facecolor='none', edgecolor='white', linewidth=1.0)
    ax_hi.axis('off')

    # 6. Final Aesthetic Touches & Colorbar
    sm = plt.cm.ScalarMappable(cmap=cmap_chosen, norm=plt.Normalize(vmin=0, vmax=VMAX))
    sm._A = []

    cax = fig.add_axes([0.1, 0.15, 0.015, 0.6])
    cbar = fig.colorbar(sm, cax=cax)
    cbar.set_label('Height (meters)', fontsize=18, fontweight='bold', labelpad=20)
    cbar.ax.tick_params(labelsize=14)

    # National Data Summary Text Box
    max_row = df.loc[df['canopy_height_max'].idxmax()]
    stats_text = (
        f"US National Summary (CHMv2)\n"
        f"──────────────────────────\n"
        f"National Max: {max_row['canopy_height_max']}m ({max_row['NAME']} County, {max_row['STATEFP']})\n"
        f"Alaska Max: {df[df['STATEFP'] == '02']['canopy_height_max'].max()}m\n"
        f"National Mean: {df['canopy_height_max'].mean():.1f}m\n"
        f"Counties Mapped: {df['GEOID'].nunique():,}"
    )
    props = dict(boxstyle='round,pad=1.0', facecolor='white', alpha=0.9, edgecolor='gray', linewidth=1.5)

    ax_48.text(0.5, 0.05, stats_text, transform=ax_48.transAxes, fontsize=16,
                verticalalignment='bottom', horizontalalignment='center', bbox=props, fontfamily='monospace')

    # 7. Save and Preview
    save_file = os.path.join(SAVE_DIR, "Fig7_NASA_Style_National_Map.png")
    plt.savefig(save_file, bbox_inches='tight', dpi=300)
