def clean_and_format(df, dataset_name):
    """Strips bloat, enforces 5-digit GEOID, and prefixes ML features."""

    # 1. Drop Census bloat BEFORE renaming anything
    df = df.drop(columns=[c for c in BLOAT_COLS if c in df.columns], errors='ignore')

    # 2. Enforce 5-digit string GEOID
    if 'GEOID' in df.columns:
        df['GEOID'] = df['GEOID'].astype(str).str.zfill(5)

    # 3. Apply ML Prefixes to all feature columns
    # We define the core keys that should NEVER be prefixed
    core_keys = ['GEOID', 'year', 'STATEFP', 'COUNTYFP', 'NAME']

    # Safely get the assigned prefix, or default to the first 4 letters if missing
    prefix = PREFIX_MAP.get(dataset_name, f"{dataset_name[:4].upper()}_")

    rename_dict = {}
    for col in df.columns:
        if col not in core_keys:
            # Only add prefix if it isn't already there (prevents double prefixing on re-runs)
            if not col.startswith(prefix):
                rename_dict[col] = f"{prefix}{col}"

    # Apply the renaming
    df = df.rename(columns=rename_dict)

    return df

