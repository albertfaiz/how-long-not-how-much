    df = pd.read_csv(csv_path, dtype={'GEOID': str})

    # 2. Fuzzy Column Finder (Robust against GEE Reducer suffix variations)
    def get_col(keyword):
        matches = [c for c in df.columns if keyword in c and 'mean' in c]
        if not matches: # Fallback if 'mean' isn't there
            matches = [c for c in df.columns if keyword in c]
        return matches[0] if matches else None

    # Dynamically locate the best column for each dataset
    c_heat = get_col('PRISM_days_tmax_over_35C')
    c_pdsi = get_col('TERRA_pdsi_worst_month')
    c_econ = get_col('ECON_nightlights')
    c_air  = get_col('AIR_no2')
    c_dem  = get_col('DEM_elevation')
    c_chm  = get_col('META_canopy_height')
    c_soil = get_col('SOIL_clay_0cm')
    c_ghm  = get_col('GHM_ghm')

    # ---------------------------------------------------------
    # FIGURE 1: CLIMATE & WATER (PRISM & TerraClimate)
    # ---------------------------------------------------------
    if c_heat and c_pdsi and 'year' in df.columns:
        fig, axes = plt.subplots(1, 2, figsize=(15, 6), dpi=300)

        # Panel A: PRISM (Heat Extremes)
        sns.lineplot(data=df, x='year', y=c_heat, color='darkred', marker='o', linewidth=2, ax=axes[0])
        axes[0].set_title('A. PRISM: Extreme Heat Trends', fontweight='bold')
        axes[0].set_ylabel('Days > 35°C (95°F)')

        # Panel B: TerraClimate (Drought)
        sns.lineplot(data=df, x='year', y=c_pdsi, color='saddlebrown', marker='s', linewidth=2, ax=axes[1])
        axes[1].axhline(0, color='gray', linestyle='--')
        axes[1].set_title('B. TerraClimate: Worst-Month Drought Severity', fontweight='bold')
        axes[1].set_ylabel('PDSI (Negative = Drought)')

        for ax in axes: ax.set_xticks(range(2000, 2024, 3))

        plt.tight_layout()
        plt.savefig(os.path.join(SAVE_DIR, "Fig1_Climate_Water.png"))
        plt.show()

    # ---------------------------------------------------------
    # FIGURE 2: ANTHROPOGENIC FOOTPRINT (Nightlights & Pollution)
    # ---------------------------------------------------------
    if c_econ and c_air and 'year' in df.columns:
        fig, axes = plt.subplots(1, 2, figsize=(15, 6), dpi=300)

        # Panel A: Nightlights (Post-2014)
        df_econ = df.dropna(subset=[c_econ])
        if not df_econ.empty:
            sns.lineplot(data=df_econ, x='year', y=c_econ, color='gold', marker='D', markeredgecolor='k', linewidth=2, ax=axes[0])
            axes[0].set_title('A. VIIRS: Economic/Urban Growth Proxy', fontweight='bold')
            axes[0].set_ylabel('Nighttime Radiance')
            axes[0].set_xticks(range(2014, 2024, 2))

        # Panel B: Pollution (Post-2019)
        df_air = df.dropna(subset=[c_air])
        if not df_air.empty:
            sns.boxplot(data=df_air, x='year', y=c_air, palette='magma', ax=axes[1])
            axes[1].set_title('B. Sentinel-5P: NO2 Air Pollution', fontweight='bold')
            axes[1].set_ylabel('NO2 Column Density')

        plt.tight_layout()
        plt.savefig(os.path.join(SAVE_DIR, "Fig2_Human_Footprint.png"))
        plt.show()

    # ---------------------------------------------------------
    # FIGURE 3: BIOPHYSICAL STRUCTURE (Meta CHM & Copernicus DEM)
    # ---------------------------------------------------------
    # These are static datasets, so we drop duplicate years to plot actual spatial distributions
    if c_chm:
        df_static = df.drop_duplicates(subset=['GEOID']).copy()

        # If DEM successfully extracted, plot Elevation vs Canopy
        if c_dem:
            plt.figure(figsize=(10, 6), dpi=300)
            sns.scatterplot(data=df_static, x=c_dem, y=c_chm, hue=c_chm, palette='viridis', size=c_chm, sizes=(20, 150), alpha=0.7)
            plt.title('Fig 3. Forest Structure vs. Elevation (Meta CHM & Copernicus DEM)', fontweight='bold')
            plt.xlabel('Elevation (meters)')
            plt.ylabel('Mean Canopy Height (meters)')
            plt.legend([],[], frameon=False) # Hide cluttered legend

            plt.tight_layout()
            plt.savefig(os.path.join(SAVE_DIR, "Fig3_Canopy_vs_Elevation.png"))
            plt.show()
        else:
            # Fallback if DEM was missing: Just plot Canopy Height Distribution
            plt.figure(figsize=(10, 6), dpi=300)
            sns.histplot(data=df_static, x=c_chm, kde=True, color='forestgreen')
            plt.title('Fig 3. Distribution of Meta Canopy Heights', fontweight='bold')
            plt.xlabel('Mean Canopy Height (meters)')
            plt.show()

    # ---------------------------------------------------------
    # FIGURE 4: THE FOUNDATION (Soil Profile & Human Modification)
    # ---------------------------------------------------------
    if c_soil and c_ghm:
        df_static = df.drop_duplicates(subset=['GEOID']).copy()

        plt.figure(figsize=(10, 6), dpi=300)
        # Bivariate density plot showing where heavily modified areas sit regarding soil type
        sns.kdeplot(data=df_static, x=c_soil, y=c_ghm, cmap="YlOrBr", fill=True, thresh=0.05)
        sns.scatterplot(data=df_static, x=c_soil, y=c_ghm, color="black", alpha=0.5, s=15)

        plt.title('Fig 4. Human Settlement vs. Soil Quality (GHM & OpenLandMap)', fontweight='bold')
        plt.xlabel('Surface Clay Fraction (%)')
        plt.ylabel('Global Human Modification Index')

        plt.tight_layout()
        plt.savefig(os.path.join(SAVE_DIR, "Fig4_Soil_vs_Modification.png"))
        plt.show()

    print("✓ Successfully generated multi-domain visualizations.")

