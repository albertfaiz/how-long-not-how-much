def preserve_keys(feature):
    state_str = ee.String(feature.get('STATEFP'))
    county_str = ee.String(feature.get('COUNTYFP'))
    state_num = ee.Number.parse(state_str)
    county_num = ee.Number.parse(county_str)
    state_padded = state_num.format('%02d')
