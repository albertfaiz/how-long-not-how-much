def process_landsat57(year):
    """Safely merges Landsat 5 & 7 and calculates Agricultural Indices"""
    start, end = f'{year}-01-01', f'{year}-12-31'

    # FIX 1: Explicitly select ONLY the bands we need BEFORE merging
    # This guarantees the schemas match and GEE doesn't drop the QA_PIXEL band
    keep_bands = ['SR_B1', 'SR_B2', 'SR_B3', 'SR_B4', 'SR_B5', 'SR_B7', 'QA_PIXEL']

    l5 = ee.ImageCollection('LANDSAT/LT05/C02/T1_L2').filterDate(start, end).select(keep_bands)
    l7 = ee.ImageCollection('LANDSAT/LE07/C02/T1_L2').filterDate(start, end).select(keep_bands)

    col = l5.merge(l7)

    def mask_and_scale(image):
        """Standardized Collection 2 Cloud Masking"""
        qa = image.select('QA_PIXEL')
        mask = qa.bitwiseAnd(1 << 1).eq(0) \
            .And(qa.bitwiseAnd(1 << 2).eq(0)) \
            .And(qa.bitwiseAnd(1 << 3).eq(0)) \
            .And(qa.bitwiseAnd(1 << 4).eq(0))

        # Only scale the optical bands (prevents destroying QA logic)
        optical = image.select('SR_B.').multiply(0.0000275).add(-0.2)
        return image.addBands(optical, overwrite=True).updateMask(mask)

    def add_indices(img):
        # Correct band mapping for Landsat 5 & 7 (NIR is Band 4, not Band 5)
        nir, red, green, swir1, blue = 'SR_B4', 'SR_B3', 'SR_B2', 'SR_B5', 'SR_B1'

        ndvi = img.normalizedDifference([nir, red]).rename('NDVI')
        evi = img.expression(
            '2.5 * ((NIR - RED) / (NIR + 6 * RED - 7.5 * BLUE + 1))',
            {'NIR': img.select(nir), 'RED': img.select(red), 'BLUE': img.select(blue)}
        ).rename('EVI')
        savi = img.expression(
            '((NIR - RED) / (NIR + RED + 0.5)) * 1.5',
            {'NIR': img.select(nir), 'RED': img.select(red)}
        ).rename('SAVI')
        ndwi = img.normalizedDifference([green, nir]).rename('NDWI')
        ndmi = img.normalizedDifference([nir, swir1]).rename('NDMI')
        bsi = img.expression(
            '((SWIR + RED) - (NIR + BLUE)) / ((SWIR + RED) + (NIR + BLUE))',
            {'SWIR': img.select(swir1), 'RED': img.select(red), 'NIR': img.select(nir), 'BLUE': img.select(blue)}
        ).rename('BSI')

        return img.addBands([ndvi, evi, savi, ndwi, ndmi, bsi])

    # Mask, add indices, and take the median composite for the year
    composite = col.map(mask_and_scale).map(add_indices).median()

    # Strip out the QA_PIXEL before returning so we only export useful ML data
    bands_to_keep = ['SR_B1', 'SR_B2', 'SR_B3', 'SR_B4', 'SR_B5', 'SR_B7',
                     'NDVI', 'EVI', 'SAVI', 'NDWI', 'NDMI', 'BSI']

    return composite.select(bands_to_keep)

