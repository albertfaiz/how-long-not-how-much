def process_prism(year):
    col = ee.ImageCollection('OREGONSTATE/PRISM/ANd').filterDate(f'{year}-01-01', f'{year}-12-31')
    means = col.select(['tmean', 'tmax', 'tmin', 'tdmean', 'vpdmin', 'vpdmax']).mean()
    precip_sum = col.select('ppt').sum().rename('ppt_sum')

    hot_days = col.map(lambda img: img.select('tmax').gt(35).rename('days_tmax_over_35C')).sum()
    frost_days = col.map(lambda img: img.select('tmin').lt(0).rename('days_tmin_under_0C')).sum()
    warm_nights = col.map(lambda img: img.select('tmin').gt(20).rename('days_tmin_over_20C')).sum()

    summer = col.filter(ee.Filter.calendarRange(6, 8, 'month'))
    winter = col.filter(ee.Filter.calendarRange(12, 2, 'month'))

    summer_means = summer.select(['tmean', 'tmax']).mean().rename(['summer_tmean', 'summer_tmax'])
    summer_precip = summer.select('ppt').sum().rename('summer_ppt_sum')
    winter_means = winter.select(['tmean', 'tmin']).mean().rename(['winter_tmean', 'winter_tmin'])
    winter_precip = winter.select('ppt').sum().rename('winter_ppt_sum')

    return means.addBands([precip_sum, hot_days, frost_days, warm_nights, summer_means, summer_precip, winter_means, winter_precip])

def process_terraclimate(year):
    col = ee.ImageCollection('IDAHO_EPSCOR/TERRACLIMATE').filterDate(f'{year}-01-01', f'{year}-12-31')
    # FIX: Replaced 'ws' with 'vs' (Wind Speed) to prevent silent crashes
    means = col.select(['aet', 'def', 'pet', 'ro', 'soil', 'swe', 'srad', 'vs']).mean()
    pdsi_min = col.select('pdsi').min().rename('pdsi_worst_month')
    pdsi_max = col.select('pdsi').max().rename('pdsi_best_month')
    return means.addBands([pdsi_min, pdsi_max])

def process_dem():
    dem = ee.ImageCollection('COPERNICUS/DEM/GLO30').mosaic().select('DEM')
    terrain = ee.Terrain.products(dem)
    return terrain.select(['elevation', 'slope', 'aspect', 'hillshade'])

def process_soil():
    def get_soil(url, name):
        img = ee.Image(url)
        return img.select('b0').rename(f'{name}_0cm').addBands(img.select('b30').rename(f'{name}_30cm'))

    sand = get_soil("OpenLandMap/SOL/SOL_SAND-WFRACTION_USDA-3A1A1A_M/v02", "sand")
    clay = get_soil("OpenLandMap/SOL/SOL_CLAY-WFRACTION_USDA-3A1A1A_M/v02", "clay")
    ph = get_soil("OpenLandMap/SOL/SOL_PH-H2O_USDA-4C1A2A_M/v02", "ph")
    org_c = get_soil("OpenLandMap/SOL/SOL_ORGANIC-CARBON_USDA-6A1C_M/v02", "org_carbon")
    bulk_d = get_soil("OpenLandMap/SOL/SOL_BULKDENS-FINEEARTH_USDA-4A1H_M/v02", "bulk_density")
    return sand.addBands([clay, ph, org_c, bulk_d])

def process_pollution(year):
    no2 = ee.ImageCollection("COPERNICUS/S5P/NRTI/L3_NO2").filterDate(f'{year}-01-01', f'{year}-12-31').select('NO2_column_number_density').mean().rename('no2_mean')
    co = ee.ImageCollection("COPERNICUS/S5P/NRTI/L3_CO").filterDate(f'{year}-01-01', f'{year}-12-31').select('CO_column_number_density').mean().rename('co_mean')
    aerosol = ee.ImageCollection("COPERNICUS/S5P/NRTI/L3_AER_AI").filterDate(f'{year}-01-01', f'{year}-12-31').select('absorbing_aerosol_index').mean().rename('aerosol_index')
    return no2.addBands([co, aerosol])

def process_chm():
    """Meta Canopy Height Map v2 & Coverage Proxies"""
    chm = ee.ImageCollection('projects/meta-forest-monitoring-okw37/assets/CanopyHeight').mosaic().select([0]).rename('canopy_height')
    cover_1m = chm.gte(1).rename('canopy_cover_1m')
    cover_5m = chm.gte(5).rename('canopy_cover_5m')
    return chm.addBands([cover_1m, cover_5m])

