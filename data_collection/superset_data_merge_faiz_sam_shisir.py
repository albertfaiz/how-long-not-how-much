def standardize_fips(row):
    """Robustly assigns and formats a 5-digit FIPS code."""
    fips_val = row.get('fips')

    # If FIPS is valid and exists, format it
    if pd.notna(fips_val) and str(fips_val).strip() != '':
        # Remove decimals if it was read as float, then zfill
        clean_fips = str(fips_val).replace('.0', '').strip()
        return clean_fips.zfill(5)

    # If FIPS is missing, try to generate it from County and State
    if 'County' in row and 'State' in row:
        if pd.notna(row['County']) and pd.notna(row['State']):
            generated_fips = af.get_county_fips(row['County'], row['State'])
            if generated_fips:
                return str(generated_fips).zfill(5)

    return np.nan # Return NaN if it absolutely cannot be resolved

def apply_prefix(col_name):
    """Applies the correct domain signature to a column name."""
    col_lower = col_name.lower()

    # Skip core keys
    if col_lower in ['fips', 'year', 'county', 'state']:
        return col_name

    # Check against domains
    for prefix, keywords in PREFIX_MAP.items():
        if any(kw in col_lower for kw in keywords):
            # Prevent double prefixing if it somehow already has it
            if not col_lower.startswith(prefix):
                return f"{prefix}{col_name}"
            return col_name

    # Default fallback for target variables or uncategorized items (e.g., smoking rate)
    if 'smoking' in col_lower or 'cancer' in col_lower:
        if not col_lower.startswith('health_'):
            return f"health_{col_name}"

    return col_name

def clean_dataframe(df, name="Dataset"):
    """Applies all cleaning, dropping, and prefixing logic to a single DataFrame."""
    print(f"--- Processing {name} ---")

    # 1. Standardize column names (lowercase 'year' and 'fips' to ensure merging works)
    df.rename(columns=lambda x: 'fips' if x.lower().strip() == 'fips' else x, inplace=True)
    df.rename(columns=lambda x: 'year' if x.lower().strip() == 'year' else x, inplace=True)

    # 2. Generate and standardize FIPS
    if 'fips' not in df.columns:
        df['fips'] = np.nan
    df['fips'] = df.apply(standardize_fips, axis=1)

    # Drop rows where we absolutely couldn't resolve FIPS or Year
    df.dropna(subset=['fips', 'year'], inplace=True)
    df['year'] = df['year'].astype(int)

    # 3. Drop Life Expectancy and Livestock columns
    cols_to_drop = []
    for col in df.columns:
        if any(drop_kw in col.lower() for drop_kw in DROP_KEYWORDS):
            cols_to_drop.append(col)

    # Also drop string-based geographic identifiers to save space now that we have exact FIPS
    if 'County' in df.columns: cols_to_drop.append('County')
    if 'State' in df.columns: cols_to_drop.append('State')

    df.drop(columns=cols_to_drop, inplace=True, errors='ignore')
    print(f"Dropped {len(cols_to_drop)} columns (LE/Livestock/Geo-Strings).")

    # 4. Apply domain signatures
    df.rename(columns=lambda x: apply_prefix(x), inplace=True)

    return df

